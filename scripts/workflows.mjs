import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { AI_TOOLS } from '../node_modules/@fission-ai/openspec/dist/core/config.js';
import { ALL_WORKFLOWS } from '../node_modules/@fission-ai/openspec/dist/core/profiles.js';

// These internal imports are intentionally tied to the pinned OpenSpec version.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tools = AI_TOOLS.filter(tool => tool.available && tool.skillsDir && !tool.globalSkillsDir);
const isolatedConfig = await mkdtemp(resolve(tmpdir(), 'backstage-openspec-'));
try {
  await mkdir(resolve(isolatedConfig, 'openspec'));
  await writeFile(resolve(isolatedConfig, 'openspec/config.json'), JSON.stringify({
    profile: 'custom', delivery: 'both', workflows: ALL_WORKFLOWS,
  }));
  const result = spawnSync(process.execPath, [
    resolve(root, 'node_modules/@fission-ai/openspec/bin/openspec.js'),
    'init', root, '--tools', tools.map(tool => tool.value).join(','),
    '--profile', 'custom', '--no-animation', '--no-copilot-cloud',
  ], { cwd: root, stdio: 'inherit', env: {
    ...process.env, XDG_CONFIG_HOME: isolatedConfig, DO_NOT_TRACK: '1', CI: '1',
  } });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`OpenSpec init exited ${result.status}`);
  const rows = tools.map(tool => `| ${tool.name} | \`${tool.value}\` | \`${tool.skillsDir}/skills/\` |`).join('\n');
  await mkdir(resolve(root, 'docs'), { recursive: true });
  await writeFile(resolve(root, 'docs/supported-agents.md'), `# Generated OpenSpec agent integrations\n\nGenerated by \`npm run workflows:sync\` using the pinned OpenSpec version.\nAll ${tools.length} repository-scoped targets are included, with every workflow.\nSeveral targets share the same physical skill directory.\n\n| Agent | OpenSpec tool ID | Skills directory |\n| --- | --- | --- |\n${rows}\n\nMiniMax Code uses global skills and is opt-in: run \`npm run openspec -- init --tools minimax-code\` if you want to modify your user-level MiniMax setup.\nHermes needs this repo's \`.hermes/skills\` added to \`skills.external_dirs\` in its user configuration.\nSome editor integrations need an editor restart. See the [upstream tool guide](https://github.com/Fission-AI/OpenSpec/blob/main/docs/supported-tools.md).\n\nWorkflow integrations are separate from constitution loading. See \`governance/adapters.json\` for the instruction files maintained here. For a tool without a native constitution adapter, explicitly attach \`AGENTS.md\`.\n`);
} finally {
  await rm(isolatedConfig, { recursive: true, force: true });
}
